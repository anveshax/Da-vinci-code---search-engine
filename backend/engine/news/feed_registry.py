def get_feeds(country: Optional[str] = None, category: Optional[str] = None, language: Optional[str] = None) -> List[Dict[str, Any]]:
    """Filters feeds matching given criteria."""
    results = FEED_REGISTRY
    if country and country.upper() != "WORLD":
        results = [f for f in results if f["country"] == country.upper()]
    if category and category.lower() != "all" and category.lower() != "top":
        results = [f for f in results if f["category"] == category.lower()]
    if language and language.lower() != "all":
        results = [f for f in results if f["language"] == language.lower()]
    return results
